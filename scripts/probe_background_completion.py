#!/usr/bin/env python
"""Live-probe background completion delivery against configured Provider Models.

The harness makes the first Model step deterministic: it synthesizes one Tool Call,
executes a probe Tool that submits three Bash-shaped completion notices, then sends
the next request through the real configured Provider adapter. It prints structural
measurements only — never credentials, prompts, completion bodies, generated text,
Tool arguments, or raw Provider responses.

Examples:
    python scripts/probe_background_completion.py
    python scripts/probe_background_completion.py --target openai --mode stream
    python scripts/probe_background_completion.py --repeat 3
"""

