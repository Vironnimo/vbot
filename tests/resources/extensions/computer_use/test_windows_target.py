def test_running_apps_merge_into_installed_apps_by_key_then_name():
    index = StartIndex(start_rows(), WINDOWS)
    apps = _win_apps.merge_apps(
        index.apps,
        [
            running("Visual Studio Code", CODE),
            running("Python", "C:\\Python314\\python.exe"),
            running("Python", "C:\\Project\\.venv\\Scripts\\python.exe"),
            _win_apps.OWN_APP,
        ],
    )
    by_name = {app.name: app for app in apps}

    assert [app.name for app in apps] == sorted(by_name, key=str.casefold)
    assert len(apps) == len(index.apps) + 1
    assert by_name["Visual Studio Code"].running
    assert not by_name["Calculator"].running
    assert by_name["Python"].keys == {
        "c:\\python314\\python.exe",
        "c:\\project\\.venv\\scripts\\python.exe",
    }
    assert by_name["vBot"].running and by_name["vBot"].launchable
    assert by_name["Calculator"].launchable


def test_start_apps_discover_once_per_period_without_blocking_callers():
    now = [0.0]
    discovered = [threading.Event(), threading.Event()]
    release = threading.Event()
    calls: list[int] = []

    def discover() -> list[StartRow]:
        calls.append(len(calls))
        discovered[min(len(calls), 2) - 1].set()
        if len(calls) > 1:
            release.wait(5)
            return [*start_rows(), StartRow("Paint", "Paint", "C:\\Paint\\paint.exe")]
        return start_rows()

    start = StartApps(discover, period=60, clock=lambda: now[0], windows_dir=WINDOWS)
    first = start.index(wait=5)
    assert {app.name for app in first.apps} >= {"Visual Studio Code"}
    now[0] = 59
    assert start.index() is first and len(calls) == 1

    now[0] = 60
    assert start.index() is first  # stale: the refresh runs in the background
    assert discovered[1].wait(5)
    release.set()
    _join_discovery()
    assert "Paint" in {app.name for app in start.index().apps}
    assert len(calls) == 2


def test_failed_start_discovery_yields_no_apps_and_warns_once(caplog):
    now = [0.0]

    def discover() -> list[StartRow]:
        raise OSError("powershell missing")

    start = StartApps(discover, period=60, clock=lambda: now[0], windows_dir=WINDOWS)
    with caplog.at_level(logging.WARNING, logger="vbot.extensions.computer_use"):
        assert start.index(wait=5).apps == ()
        now[0] = 120
        start.index()
        _join_discovery()

    warnings = [record.getMessage() for record in caplog.records]
    assert warnings == ["Start menu app discovery failed (error=OSError)"]


def test_displays_are_ordered_primary_first_with_unique_names():
    monitors = [
        Monitor("\\\\.\\DISPLAY3", 2560, 0, 4480, 1080, primary=False, dpi=96),
        Monitor("\\\\.\\DISPLAY1", -1920, 270, 0, 1350, primary=False, dpi=96),
        Monitor("\\\\.\\DISPLAY2", 0, 0, 2560, 1440, primary=True, dpi=120),
    ]
    names = {"\\\\.\\DISPLAY1": "LG ULTRAGEAR", "\\\\.\\DISPLAY2": "LG ULTRAGEAR"}

    displays = name_displays(monitors, names)

    assert [(display.name, display.id) for display in displays] == [
        ("LG ULTRAGEAR (1)", "\\\\.\\DISPLAY2"),
        ("LG ULTRAGEAR (2)", "\\\\.\\DISPLAY1"),
        ("Display 3", "\\\\.\\DISPLAY3"),
    ]
    assert (displays[0].width, displays[0].height, displays[0].scale_percent) == (2560, 1440, 125)
    assert (displays[1].left, displays[1].top, displays[1].scale_percent) == (-1920, 270, 100)


def _join_discovery() -> None:
    for thread in threading.enumerate():
        if thread.name == "computer-use-start-apps":
            thread.join(5)
