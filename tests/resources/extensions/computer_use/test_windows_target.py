@pytest.mark.parametrize(
    "origin,size", [(0, 1), (0, 1080), (-1920, 4480), (-3840, 7680), (270, 1440)]
)
def test_absolute_mouse_coordinates_land_on_the_requested_pixel(origin, size):
    for position in range(origin, origin + size):
        normalized = _win_input.absolute_coordinate(position, origin, size)
        assert 0 <= normalized <= 65535
        assert origin + normalized * size // 65536 == position  # how Windows maps it back


